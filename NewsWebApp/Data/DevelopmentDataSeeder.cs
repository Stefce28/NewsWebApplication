        };

        foreach (var category in categories)
        {
            var exists = await context.Categories.AnyAsync(c => c.Name == category.Key);

            if (!exists)
            {
                context.Categories.Add(new Category(category.Key, category.Value));
            }
        }

        await context.SaveChangesAsync();
    }

